/** Compare transport representations without dropping text, unknown markers or differing sticker identities. */
export function legacyUserText(text: string): string {
  return text.replace(/\[sticker:([^\]]+)\]/g, (marker, id: string) => {
    const description = Object.hasOwn(DESCRIPTIONS, id) ? DESCRIPTIONS[id].phrases[0] : undefined;
    return description ? `（用户发送表情包：${description}）` : marker;
  });
}